#!/usr/bin/env python3
"""Pack a Flash project so its index.html opens straight from disk (file://).

usage: build-offline.py <project dir> [<dir with downloaded Ruffle files>]

Writes offline-data.js (every .swf/.xml and pics/* as base64) and, when a Ruffle
download is given, ruffle/ with the player and its .wasm wrapped in scripts.
Re-run after changing the XML or the pictures.
"""
import base64, json, os, shutil, sys

proj = sys.argv[1]
b64 = lambda p: base64.b64encode(open(p, 'rb').read()).decode()

if len(sys.argv) > 2:
    src, out = sys.argv[2], os.path.join(proj, 'ruffle')
    os.makedirs(out, exist_ok=True)
    for f in os.listdir(src):
        if f.endswith('.js') or f.startswith('LICENSE'):
            shutil.copy(os.path.join(src, f), out)
        elif f.endswith('.wasm'):
            open(os.path.join(out, f + '.js'), 'w').write('window.__offline[%s] = "%s";\n' % (json.dumps('ruffle/' + f), b64(os.path.join(src, f))))

names = sorted(f for f in os.listdir(proj) if f.lower().endswith(('.swf', '.xml')))
names += sorted('pics/' + f for f in os.listdir(os.path.join(proj, 'pics')) if not f.startswith('.'))
with open(os.path.join(proj, 'offline-data.js'), 'w') as fh:
    fh.write('// Generated by build-offline.py: the movie and everything it loads, so the page works from file://\n')
    fh.write('window.__offline = ' + json.dumps({n: b64(os.path.join(proj, n)) for n in names}, indent=0) + ';\n')
print(len(names), 'resources,', os.path.getsize(os.path.join(proj, 'offline-data.js')), 'bytes')
